"""Stage D support (plan §9): export actor weights to float32 C headers for an on-device
equivalence test, and report each actor's size against a 512 KB flash budget.

  python export_c.py --results R1.json [R2.json ...] --models DIR --out DIR [--vectors 20]

Per actor it writes <out>/<label>_actor.h holding:
  - every parameter tensor as `static const float <name>[]` (row-major, PyTorch layout),
  - the trunk hyper-parameters and the fixed recursion buffers (TRM H_init/L_init),
  - N reference (input, output) vector pairs from PyTorch (deterministic actor, float32),
and <out>/export_summary.json with parameter count and FP32 / INT8 weight size.
INT8 size is the weights at 1 byte each plus one float32 scale per tensor (per-tensor
symmetric quantisation); buffers stay float32 in both.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

REPO = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO / "src"))

from eval import load_actor, make_env  # noqa: E402

FLASH_BUDGET = 512 * 1024


def _c_name(name: str) -> str:
    return name.replace(".", "_")


def _array(name: str, t: np.ndarray) -> str:
    flat = t.astype(np.float32).ravel()
    body = ",\n  ".join(", ".join(f"{x:.9e}f" for x in flat[i:i + 6]) for i in range(0, len(flat), 6))
    dims = "x".join(str(d) for d in t.shape) or "scalar"
    return f"/* {dims} */\nstatic const float {name}[{len(flat)}] = {{\n  {body}\n}};\n"


def export(summary_path: Path, models: Path, out: Path, n_vec: int) -> dict:
    summary = json.loads(summary_path.read_text())
    actor, cfg, _ = load_actor(summary, models, "cpu")
    label = f"{summary['model']}_{summary['env_id']}_seed{summary['seed']}".replace("-", "_")
    params = dict(actor.named_parameters())
    buffers = dict(actor.named_buffers())

    env = make_env(cfg)
    rng = np.random.default_rng(0)
    xs = []
    obs, _ = env.reset(seed=123)
    for _ in range(n_vec):   # inputs = observations actually visited by the deterministic policy
        xs.append(np.asarray(obs, dtype=np.float32))
        with torch.no_grad():
            a = actor(torch.tensor(obs, dtype=torch.float32).unsqueeze(0)).numpy()[0]
        obs, _, term, trunc, _ = env.step(a)
        if term or trunc:
            obs, _ = env.reset(seed=int(rng.integers(1 << 30)))
    env.close()
    X = np.stack(xs)
    with torch.no_grad():
        Y = actor(torch.tensor(X)).numpy()

    guard = f"{label.upper()}_ACTOR_H"
    lines = [f"/* Auto-generated by experiments/phase4/export_c.py from {summary_path.name} (model_id {summary['model_id']}). */",
             f"#ifndef {guard}", f"#define {guard}", "",
             f"/* model: {summary['model']}  obs_dim: {X.shape[1]}  act_dim: {Y.shape[1]}  action_limit: {float(actor.action_limit)} */"]
    for k, v in OmegaConfToDict(cfg.model).items():
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            lines.append(f"#define {label.upper()}_{k.upper()} {v}")
    lines.append("")
    for name, p in params.items():
        lines.append(_array(_c_name(name), p.detach().numpy()))
    for name, b in buffers.items():
        lines.append(_array(_c_name(name), b.detach().numpy()))
    lines.append(f"#define {label.upper()}_N_REF {n_vec}")
    lines.append(_array("ref_inputs", X))
    lines.append(_array("ref_outputs", Y))
    lines.append(f"#endif /* {guard} */")
    (out / f"{label}_actor.h").write_text("\n".join(lines) + "\n")

    n_params = sum(p.numel() for p in params.values())
    n_buf = sum(b.numel() for b in buffers.values())
    fp32 = 4 * (n_params + n_buf)
    int8 = n_params + 4 * len(params) + 4 * n_buf
    return {"label": label, "source": summary_path.name, "model": summary["model"], "actor_params": n_params,
            "buffer_floats": n_buf, "fp32_bytes": fp32, "int8_bytes": int8,
            "fp32_fits_512KB": fp32 <= FLASH_BUDGET, "int8_fits_512KB": int8 <= FLASH_BUDGET,
            "header": f"{label}_actor.h", "ref_vectors": n_vec}


def OmegaConfToDict(c) -> dict:
    from omegaconf import OmegaConf
    return OmegaConf.to_container(c, resolve=True)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, nargs="+", required=True)
    ap.add_argument("--models", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--vectors", type=int, default=20)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    rows = [export(r, a.models, a.out, a.vectors) for r in a.results]
    (a.out / "export_summary.json").write_text(json.dumps(rows, indent=1) + "\n")
    for r in rows:
        print(f"{r['label']}: {r['actor_params']:,} params, FP32 {r['fp32_bytes'] / 1024:.1f} KB, "
              f"INT8 {r['int8_bytes'] / 1024:.1f} KB (512 KB budget: FP32 {'fits' if r['fp32_fits_512KB'] else 'over'}, "
              f"INT8 {'fits' if r['int8_fits_512KB'] else 'over'})")


if __name__ == "__main__":
    main()
